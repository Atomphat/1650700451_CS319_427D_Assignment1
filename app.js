/* Scroll-reveal + animated skill bars */
const revealEls = document.querySelectorAll('.reveal');
const skillEls = document.querySelectorAll('.skill-item');

function fillSkill(el){
  const bar = el.querySelector('.skill-fill');
  if(bar) bar.style.width = (el.dataset.level || 0) + '%';
}

/* Count-up animation for the stats strip */
function finalizeCount(el){
  const target = parseFloat(el.dataset.count);
  const decimals = parseInt(el.dataset.decimals || '0', 10);
  if(!Number.isNaN(target)) el.textContent = target.toFixed(decimals);
}
function animateCount(el){
  const target = parseFloat(el.dataset.count);
  const decimals = parseInt(el.dataset.decimals || '0', 10);
  if(Number.isNaN(target) || reduceMotion){ finalizeCount(el); return; }
  const duration = 1200;
  const start = performance.now();
  (function tick(now){
    const p = Math.min((now - start) / duration, 1);
    const eased = 1 - Math.pow(1 - p, 3);
    el.textContent = (target * eased).toFixed(decimals);
    if(p < 1) requestAnimationFrame(tick);
    else finalizeCount(el);
  })(start);
}
function fillStats(el){
  el.querySelectorAll('.stat-value').forEach(animateCount);
}

if(reduceMotion || !('IntersectionObserver' in window)){
  revealEls.forEach(el => el.classList.add('in-view'));
  skillEls.forEach(fillSkill);
  document.querySelectorAll('.stats-strip').forEach(fillStats);
} else {
  const io = new IntersectionObserver((entries, obs) => {
    entries.forEach(entry => {
      if(!entry.isIntersecting) return;
      entry.target.classList.add('in-view');
      if(entry.target.classList.contains('skill-item')) fillSkill(entry.target);
      if(entry.target.classList.contains('stats-strip')) fillStats(entry.target);
      obs.unobserve(entry.target);
    });
  }, { threshold: 0.15 });
  revealEls.forEach(el => io.observe(el));
  skillEls.forEach(el => io.observe(el));
}

// Make sure PDF export always shows full content, even sections never scrolled into view
window.addEventListener('beforeprint', () => {
  revealEls.forEach(el => el.classList.add('in-view'));
  skillEls.forEach(fillSkill);
  document.querySelectorAll('.stat-value').forEach(finalizeCount);
});

