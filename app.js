const reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
let currentLang = 'th';

/* Typewriter effect for the name / role in the header */
function typewrite(el, text, speed){
  return new Promise(resolve => {
    if(el._twTimer) clearTimeout(el._twTimer);
    el.classList.add('typing');
    el.textContent = '';
    let i = 0;
    (function step(){
      el.textContent = text.slice(0, i);
      i++;
      if(i <= text.length){
        el._twTimer = setTimeout(step, speed);
      } else {
        el.classList.remove('typing');
        resolve();
      }
    })();
  });
}

async function runTypewriter(){
  const d = dict[currentLang];
  const nameEl = document.querySelector('h1.tw[data-i18n-key="name"]');
  const roleEl = document.querySelector('.role.tw[data-i18n-key="role"]');
  if(!nameEl || !roleEl) return;
  if(reduceMotion){
    nameEl.textContent = d.name;
    roleEl.textContent = d.role;
    return;
  }
  await typewrite(nameEl, d.name, 55);
  await typewrite(roleEl, d.role, 22);
}

/* Break prose text into per-word <span>s so they can cascade in on reveal */
function wrapWords(el, text){
  el.innerHTML = '';
  let i = 0;
  text.split(/(\s+)/).forEach(token => {
    if(token.trim() === ''){
      el.appendChild(document.createTextNode(token));
    } else {
      const span = document.createElement('span');
      span.className = 'sw';
      span.style.setProperty('--i', i++);
      span.textContent = token;
      el.appendChild(span);
    }
  });
}

function applyLang(lang){
  document.documentElement.setAttribute('data-lang', lang);
  document.documentElement.lang = (lang==='th'?'th':'en');
  currentLang = lang;
  const d = dict[lang];
  document.querySelectorAll('[data-i18n-key]').forEach(el=>{
    if(el.classList.contains('tw')) return; // handled by the typewriter
    const k = el.getAttribute('data-i18n-key');
    if(!d[k]) return;
    if(el.classList.contains('stagger-text')) wrapWords(el, d[k]);
    else el.textContent = d[k];
  });
  localStorage.setItem('resume_lang', lang);
  runTypewriter();
}

